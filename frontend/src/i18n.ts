export const DICT: Record<Lang, Record<Key, string>> = { en, mr };

/** Look up `key` in `lang` and fill {placeholders}. Unknown keys come back unchanged (visible, not a crash). */
export function translate(lang: Lang, key: string, params: Params = {}): string {
  const text = (DICT[lang] as Record<string, string>)[key];
  if (text === undefined) return key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}
